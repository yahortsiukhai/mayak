"""
Подключение к базе данных PostgreSQL.

Этот модуль создаёт:
  1. engine — соединение с БД (пул соединений)
  2. SessionLocal — фабрика сессий (по одной на запрос)
  3. Base — базовый класс для всех моделей
"""

from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker, DeclarativeBase

from app.config import settings


# ============================================
# Создание движка (Engine)
# ============================================
# Engine — пул соединений с БД. Держит N соединений,
# переиспользует их вместо постоянного создания новых.
engine = create_engine(
    settings.database_url,   # строка подключения из .env
    echo=settings.debug,     # логировать SQL-запросы (в dev полезно)
    pool_pre_ping=True,      # проверять соединение перед использованием
    pool_size=5,             # максимум 5 соединений в пуле
    max_overflow=10,         # ещё 10 сверх пула — при пиковой нагрузке
)


# ============================================
# Фабрика сессий
# ============================================
# SessionLocal() создаёт НОВУЮ сессию для каждого запроса.
SessionLocal = sessionmaker(
    bind=engine,
    autocommit=False,        # не коммитить автоматически
    autoflush=False,         # не отправлять изменения в БД до commit
    expire_on_commit=False,  # объекты не «протухают» после commit
)


# ============================================
# Базовый класс для всех моделей
# ============================================
class Base(DeclarativeBase):
    """
    От этого класса наследуются ВСЕ модели (User, Monitor, Check).
    SQLAlchemy смотрит на наследников и создаёт по ним таблицы.
    """
    pass


# ============================================
# FastAPI-зависимость для получения сессии
# ============================================
def get_db():
    """
    Выдаёт сессию БД для одного запроса и закрывает её после.
    Используется в эндпоинтах через Depends(get_db).
    """
    db = SessionLocal()
    try:
        yield db          # отдаём сессию в эндпоинт
    finally:
        db.close()        # закрываем в любом случае